CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    CONSTRAINT UQ_USER_EMAIL UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL,
    available BOOLEAN NOT NULL,
    owner_id BIGINT,
    request_id BIGINT,
    count_rental INT DEFAULT 0,
    CONSTRAINT items_users_fk FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT items_request_fk FOREIGN KEY (request_id) REFERENCES request(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booker_id BIGINT,
    item_id BIGINT,
    status VARCHAR(50),
    start_time TIMESTAMP,
    end_time TIMESTAMP,
    CONSTRAINT bookings_items_fk FOREIGN KEY (item_id) REFERENCES  items(id) ON DELETE CASCADE,
    CONSTRAINT bookings_users_fk FOREIGN KEY (booker_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT,
    booker_id BIGINT,
    text VARCHAR,
    created TIMESTAMP,
    CONSTRAINT comments_items_fk FOREIGN KEY (item_id) REFERENCES  items(id) ON DELETE CASCADE,
    CONSTRAINT comments_users_fk FOREIGN KEY (booker_id) REFERENCES users(id) ON DELETE CASCADE
);
